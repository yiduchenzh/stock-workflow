def is_cache_valid(code):
    cf = CACHE_DIR / f"{code}.pkl"
    if not cf.exists(): return False
    age = time.time() - cf.stat().st_mtime
    return age < CACHE_TTL

def warmup():
    """预下载K线缓存"""
    from data.sources import get_kline
    ok = 0; fail = 0; cached = 0
    for i, code in enumerate(HOT_STOCKS):
        if is_cache_valid(code):
            cached += 1
            continue
        try:
            df = get_kline(code, days=200)
            if df is not None and len(df) > 10:
                with open(CACHE_DIR / f"{code}.pkl", "wb") as f:
                    pickle.dump(df, f)
                ok += 1
            else:
                fail += 1
        except:
            fail += 1
        if (i+1) % 30 == 0:
            sys.stdout.write(f"\r  [{i+1}/{len(HOT_STOCKS)}] OK={ok} 缓存={cached} 失败={fail}")
            sys.stdout.flush()
    print(f"\n预热完成: OK={ok} 缓存={cached} 失败={fail}")

if __name__ == "__main__":
    import logging; logging.basicConfig(level=logging.WARNING)
    warmup()